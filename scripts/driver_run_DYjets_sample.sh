#!/usr/bin/env bash
# Produce one DYjets sample from start to plots, unattended (e.g. overnight in tmux):
#   1. build the gridpack            -> gridpack_<sample>.tar.gz
#   2. short local test (200 events) -> <EOS>/<sample>/test/Rivet_1.yoda; stops here if it fails
#   3. submit the condor jobs         -> <EOS>/<sample>/Rivet_<seed>.yoda
#   4. wait for condor, check that every job wrote its yoda, merge, scaling files, rankings
#                                     -> <EOS>/<sample>/Rivet.yoda, <EOS>/<sample>/scaling/,
#                                        outputs/<sample>/ranking_{rate,shape}/
#   5. plots: per histogram the SM, the 3 leading operators by rate (solid) and the 3 leading by
#      shape (dashed), with their statistical uncertainties -> outputs/<sample>/plots/
#      and README.md there with the metadata of the sample (events, cross sections, settings);
#      for the three LO 13.6 TeV samples also their SM comparison -> outputs/compare_LO_13p6TeV/
#
# Usage, from the EFT2Obs folder:
#   ./scripts/driver_run_DYjets_sample.sh <sample> <LO|NLO> [jobs=50] [events/job=2000] [cores=4]
# Examples:
#   ./scripts/driver_run_DYjets_sample.sh DYjets_LO_0j_13p6TeV  LO
#   ./scripts/driver_run_DYjets_sample.sh DYjets_NLO_0j_13p6TeV NLO 100 1000
#
# <sample> is the name of the cards folder, of the MadGraph process (`output` in its proc_card.dat),
# of the EOS folder, and of outputs/<sample>. The MadGraph process folder must exist
# (setup_process.sh or setup_process_NLO.sh).
# An existing gridpack_<sample>.tar.gz is reused, so a rerun after a failed step 2-4 skips step 1.
# Condor files and logs: jobs/<sample>/. This script's own log: jobs/<sample>/driver.log.
# Start at a later step with FROM_STEP (same arguments as the first call):
#   FROM_STEP=4 ./scripts/driver_run_DYjets_sample.sh <sample> <LO|NLO> [jobs] ...   # jobs already submitted
#   FROM_STEP=5 ./scripts/driver_run_DYjets_sample.sh <sample> <LO|NLO>              # only the plots
#
# Do not edit this file while a driver runs it: bash reads the script while it runs, so an edit
# shifts what the running driver reads next. Write the new version to another file and mv it here.
set -o pipefail

# ---- Arguments and fixed settings
SAMPLE="${1:?Usage: $0 <sample> <LO|NLO> [jobs] [events/job] [cores]}"
ORDER="${2:?LO or NLO missing}"
JOBS="${3:-50}"
EVENTS="${4:-2000}"
CORES="${5:-4}"
CARDS="${SAMPLE}"
FLAVOUR="tomorrow"          # condor queue: 24 h. "workday" (8 h) was too short on 6 Nov
FIRST_SEED=1000             # job i uses seed FIRST_SEED + i -> Rivet_<seed>.yoda
FROM_STEP="${FROM_STEP:-1}"
EOS_DIR=/eos/user/m/mwitt/EFT2Obs
E="${EOS_DIR}/${SAMPLE}"    # run folder on EOS: yoda files, scaling/
GRIDPACK="gridpack_${SAMPLE}.tar.gz"
JOB_DIR="jobs/${SAMPLE}"    # condor files and logs, driver.log
OUT="outputs/${SAMPLE}"     # rankings and plots

# NLO needs --nlo in run_gridpack.py, launch_jobs.py, and scaling_DYplusJets.sh
case "${ORDER}" in
    LO) NLO_FLAG="" ;;
    NLO) NLO_FLAG="--nlo" ;;
    *) echo "ERROR: order must be LO or NLO, not ${ORDER}"; exit 1 ;;
esac

# Everything printed from here on also goes to driver.log
mkdir -p "${JOB_DIR}"
exec > >(tee -a "${JOB_DIR}/driver.log") 2>&1
step() { echo; echo "=== $(date '+%F %T') ${SAMPLE}: $*"; }
fail() { echo "ERROR: $*"; echo "=== $(date '+%F %T') ${SAMPLE}: stopped"; exit 1; }

# ---- Checks before anything runs
source env.sh
grep -qE "^output +${CARDS}\s*$" "cards/${CARDS}/proc_card.dat" \
    || fail "proc_card.dat must end with 'output ${CARDS}'"
[ -d "${MG_DIR}/${CARDS}" ] || fail "no MadGraph process ${MG_DIR}/${CARDS}: run setup_process(_NLO).sh ${CARDS} first"
# A fresh run must not mix its jobs with the yoda files of an earlier one
if [ "${FROM_STEP}" -lt 4 ]; then
    ls "${E}"/Rivet_*.yoda >/dev/null 2>&1 && fail "${E} already has Rivet_*.yoda files; use a new sample name"
fi

step "settings: cards/${CARDS}, ${ORDER}, ${JOBS} jobs x ${EVENTS} events, ${CORES} cores, from step ${FROM_STEP}"
grep -E "= *(ebeam1|ebeam2|mmll|mmllmax|use_syst|ickkw|xqcut|parton_shower)\b" "cards/${CARDS}/run_card.dat"
if [ "${ORDER}" = LO ]; then
    grep -qE "^\s*False\s*=\s*use_syst" "cards/${CARDS}/run_card.dat" \
        || fail "run_card.dat needs 'False = use_syst': the systematics weights break setup/WeightCorrector.h"
fi

# ---- Steps 1-3: gridpack, local test, condor submission
if [ "${FROM_STEP}" -lt 4 ]; then
# 1. Gridpack
if [ -f "${GRIDPACK}" ]; then
    step "1. reusing existing ${GRIDPACK}"
else
    step "1. building ${GRIDPACK}"
    if [ "${ORDER}" = LO ]; then
        # make_gridpack.sh names its output gridpack_<cards>__<sample>.tar.gz: rename it
        ./scripts/make_gridpack.sh "${CARDS}" 0 "${CORES}" "__${SAMPLE}" || fail "gridpack build failed"
        mv "gridpack_${CARDS}__${SAMPLE}.tar.gz" "${GRIDPACK}"
    else
        ./scripts/make_gridpack_NLO.sh "${CARDS}" "${CORES}" || fail "gridpack build failed"
        mv "gridpack_${CARDS}.tar.gz" "${GRIDPACK}"
    fi
    [ -f "${GRIDPACK}" ] || fail "${GRIDPACK} was not created"
fi

# 2. Local test
step "2. local test, 200 events"
# run_gridpack.py unpacks into $TMPDIR/gridpack_run_<seed>: a folder per sample, so drivers running
# in parallel do not delete each other's files
TEST_TMP="/tmp/${USER}/${SAMPLE}"
mkdir -p "${TEST_TMP}"
TMPDIR="${TEST_TMP}" python scripts/run_gridpack.py --gridpack "${GRIDPACK}" -s 1 -e 200 -p DYplusJets -o "${E}/test" ${NLO_FLAG} \
    || fail "local test failed"
[ -s "${E}/test/Rivet_1.yoda" ] || fail "local test wrote no ${E}/test/Rivet_1.yoda"

# 3. Condor
step "3. submitting ${JOBS} condor jobs (${FLAVOUR})"
touch "${JOB_DIR}/.submitted"          # step 4 then only accepts a condor log newer than this
python scripts/launch_jobs.py --gridpack "${GRIDPACK}" -j "${JOBS}" -s "${FIRST_SEED}" -e "${EVENTS}" \
    -p DYplusJets -o "${E}" ${NLO_FLAG} --job-mode condor --task-name "${SAMPLE}" --dir "${JOB_DIR}" \
    --sub-opts "+JobFlavour = \"${FLAVOUR}\"" || fail "condor_submit failed"
fi

# ---- Step 4: wait for condor, check, merge, scaling files, rankings
if [ "${FROM_STEP}" -le 4 ]; then
[ "${FROM_STEP}" -eq 4 ] && step "resuming at step 4 for the jobs already submitted"

# Find the condor log of the jobs to wait for. condor writes it a little after condor_submit
# returns: try for up to 5 min. After a fresh submission only a log newer than .submitted counts
# (not one of an earlier submission); when resuming, the newest log is the one.
for i in $(seq 30); do
    if [ "${FROM_STEP}" -lt 4 ]; then
        CONDOR_LOG=$(find "${JOB_DIR}" -maxdepth 1 -name "${SAMPLE}.*.log" -newer "${JOB_DIR}/.submitted" | head -1)
    else
        CONDOR_LOG=$(ls -t "${JOB_DIR}/${SAMPLE}".*.log 2>/dev/null | head -1)
    fi
    [ -n "${CONDOR_LOG}" ] && break
    sleep 10
done
[ -n "${CONDOR_LOG}" ] || fail "no condor log in ${JOB_DIR}"

step "4. waiting for the jobs in ${CONDOR_LOG} (at most 36 h)"
# condor_wait returns when all jobs in the log have ended; held jobs never end, hence the time limit
condor_wait -wait $((36 * 3600)) "${CONDOR_LOG}" || echo "condor_wait stopped: some jobs are not done (held?)"
# Every job must have written its yoda file; otherwise stop and leave the merging to the user
N_DONE=$(ls "${E}"/Rivet_*.yoda 2>/dev/null | wc -l)
step "${N_DONE}/${JOBS} yoda files"
grep -il traceback "${JOB_DIR}"/*.err 2>/dev/null | head
[ "${N_DONE}" -eq "${JOBS}" ] || fail "not all jobs finished: see condor_q -held and ${JOB_DIR}/*.err; merge by hand if enough"

step "merging"
yodamerge -o "${E}/Rivet.yoda" "${E}"/Rivet_*.yoda || fail "yodamerge failed"

# scaling_<histogram>.json per histogram, into ${E}/scaling/
step "scaling files"
./scripts/scaling_DYplusJets.sh "${E}" "cards/${CARDS}/config.json" ${NLO_FLAG}

# One ranking per histogram at c = 1: by the change of the rate, and by the change of the shape
# (over all bins with SM events)
step "rankings"
mkdir -p "${OUT}/ranking_rate" "${OUT}/ranking_shape"
for f in "${E}"/scaling/scaling_zj_*.json "${E}"/scaling/scaling_ll_*.json; do
    n=$(basename "$f" .json); n=${n#scaling_}
    python scripts/rank_operators.py "$f" 1 > "${OUT}/ranking_rate/$n.txt"
    python scripts/rank_operators.py "$f" 1 --sort shape > "${OUT}/ranking_shape/$n.txt"
done
fi

# ---- Step 5: plots
step "5. plots"
[ -d "${OUT}/ranking_rate" ] && [ -d "${OUT}/ranking_shape" ] \
    || fail "no rankings in ${OUT}: run step 4 first (FROM_STEP=4)"
# Plot title: model from the order, energy from the sample name (DYjets_<order>_<jets>_<energy>)
case "${SAMPLE}" in
    *_13p6TeV) ENERGY="13.6 TeV" ;;
    *_13TeV) ENERGY="13 TeV" ;;
    *) ENERGY="" ;;
esac
[ "${ORDER}" = LO ] && MODEL="SMEFTsim3" || MODEL="SMEFTatNLO"
# Left title: the generated process, from the jets in the sample name: 0j -> "0j", 01j -> "<= 1j", 012j -> "<= 2j"
PARTONS=$(echo "${SAMPLE}" | cut -d_ -f3)   # e.g. 012j
case "${PARTONS}" in
    0j) JETS="0j" ;;
    *) JETS="#leq ${PARTONS: -2}" ;;      # last digit + j
esac
PROCESS="pp #rightarrow l^{+}l^{-} + ${JETS} (${ORDER})"
# --top-ranked: each histogram gets the 3 leading operators of its own rate and shape rankings.
# Ratio panel 0.8-1.2: at c = 1 the leading rate effects are about 14 %
python scripts/plot_DYplusJets.py -i "${E}" -c "cards/${CARDS}/config.json" -o "${OUT}/plots" \
    --channels ll ee mm --show-unc --title-right "${MODEL}${ENERGY:+, ${ENERGY}}" --top-ranked "${OUT}" \
    --ratio 0.8,1.2 \
    --process-title "${PROCESS}" \
    || fail "plotting failed"

# SM of the three LO 13.6 TeV samples compared, ratio to 0j -> outputs/compare_LO_13p6TeV/
# (only after one of these samples; needs all three merged)
case "${SAMPLE}" in
    DYjets_LO_0j_13p6TeV|DYjets_LO_01j_13p6TeV|DYjets_LO_012j_13p6TeV)
        step "comparison of the LO 13.6 TeV samples"
        python scripts/plot_DYplusJets_SMsampleRatios.py -o outputs/compare_LO_13p6TeV --channels ll ee mm \
            --ratio-title "Ratio to Born" --process-title "pp #rightarrow l^{+}l^{-} (LO)" \
            --sample "LO 0j=${EOS_DIR}/DYjets_LO_0j_13p6TeV" \
            --sample "LO #kern[-1]{#leq}1j=${EOS_DIR}/DYjets_LO_01j_13p6TeV" \
            --sample "LO #kern[-1]{#leq}2j=${EOS_DIR}/DYjets_LO_012j_13p6TeV" \
            || fail "comparison failed"
        step "normalised comparison of the LO 13.6 TeV samples"
        python scripts/plot_DYplusJets_SMsampleRatios.py -o outputs/compare_LO_13p6TeV_normalised --channels ll ee mm \
            --normalise --ratio-title "Ratio to Born" --process-title "pp #rightarrow l^{+}l^{-} (LO)" \
            --sample "LO 0j=${EOS_DIR}/DYjets_LO_0j_13p6TeV" \
            --sample "LO #kern[-1]{#leq}1j=${EOS_DIR}/DYjets_LO_01j_13p6TeV" \
            --sample "LO #kern[-1]{#leq}2j=${EOS_DIR}/DYjets_LO_012j_13p6TeV" \
            || fail "normalised comparison failed"
        ;;
esac

# README.md in the plots folder: events, cross sections, cards settings, operators, code version
python scripts/write_plots_readme.py "${SAMPLE}" || fail "README failed"

step "done: ${E}/Rivet.yoda, ${E}/scaling/, ${OUT}/ranking_*, ${OUT}/plots, ${OUT}/plots/README.md"
